"""PR hygiene: a pull request states its goal, how it is achieved, and what it affects.

Run by the `pr-hygiene` CI job on every pull request event and by
`task pr:open` before anything is pushed::

    uv run python scripts/pr_check.py --title T --body-file F [--draft] [--base B] [--author L]
    uv run python scripts/pr_check.py --pr 77   # title, body, draft, base, author via gh

Rules (AGENTS.md "Working alongside other agents"):

- the title is `<Topic>: <imperative summary>`; a work-unit PR uses its id as
  the topic (`WU-NN: …`);
- the body carries the three mandatory sections of
  `.github/PULL_REQUEST_TEMPLATE.md` (Goal, How, Impact), drafts included;
- once ready for review every section present has content and no template
  placeholder remains. The optional sections (Decisions made without review,
  Open questions, Risks and not verified, How to try it) are kept only when
  they have something to say;
- a stacked PR (base other than `main`) says `Stacked on #N` in its body;
- a PR opened by a dependency bot (`dependabot[bot]`) or the standing Release
  PR (`Release: …`, generated by release-pr.yml) has a generated body: only
  its title is checked.

The body does not repeat what CI already shows: the checks, the privacy guard
(`scripts/privacy_check.py`) and the change-file policy (`scripts/release.py`)
run as their own checks.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from typing import cast

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / ".github" / "PULL_REQUEST_TEMPLATE.md"
TITLE_RE = re.compile(r"^(WU-[0-9A-Za-z]+): \S|^[A-Z][A-Za-z0-9 /&-]{1,40}: \S")
STACKED_RE = re.compile(r"\bStacked on #\d+", re.IGNORECASE)
PLACEHOLDER_RE = re.compile(r"<[A-Za-z][^>\n]* [^>\n]*>")
COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
# Code is never a placeholder: `Mapping<str, Any>` in a snippet is content.
FENCE_RE = re.compile(r"^```.*?^```", re.DOTALL | re.MULTILINE)
INLINE_CODE_RE = re.compile(r"`[^`\n]*`")
BOT_AUTHORS = frozenset({"dependabot[bot]"})
# The standing Release PR (release-pr.yml) has a generated body: like a bot PR,
# only its title is checked. Its change-file exemption lives in release.py.
GENERATED_TITLE_RE = re.compile(r"^Release: ")
MANDATORY_SECTIONS = ("## Goal", "## How", "## Impact")
OPTIONAL_SECTIONS = (
    "## Decisions made without review",
    "## Open questions",
    "## Risks and not verified",
    "## How to try it",
)


@dataclass(frozen=True, slots=True)
class Pull:
    """What the check knows about one pull request.

    Attributes:
        title: The PR title.
        body: The PR body (Markdown).
        draft: Whether the PR is still a draft.
        base: The base branch name.
        author: The author's login (bots get a title-only check).
    """

    title: str
    body: str
    draft: bool
    base: str = "main"
    author: str = ""


def template_headings() -> list[str]:
    """The `## ` headings of the PR template, in order."""
    return [
        ln.strip()
        for ln in TEMPLATE.read_text(encoding="utf-8").splitlines()
        if ln.startswith("## ")
    ]


def sections(body: str) -> dict[str, str]:
    """Split a body into `## heading` → content (HTML comments removed)."""
    out: dict[str, str] = {}
    current: str | None = None
    in_fence = False
    for ln in COMMENT_RE.sub("", body).splitlines():
        if ln.startswith("```"):
            in_fence = not in_fence
        if ln.startswith("## ") and not in_fence:
            current = ln.strip()
            out[current] = ""
        elif current is not None:
            out[current] += ln + "\n"
    return out


def without_code(text: str) -> str:
    """The text with fenced blocks and inline code spans removed."""
    return INLINE_CODE_RE.sub("", FENCE_RE.sub("", text))


def has_content(text: str) -> bool:
    """Whether a section holds at least one line that is not a template placeholder."""
    for ln in text.splitlines():
        s = ln.strip()
        if not s or s.startswith("```"):
            continue
        if PLACEHOLDER_RE.fullmatch(s) or (s.startswith("<") and s.endswith(">")):
            continue
        return True
    return False


def check(pull: Pull) -> list[str]:
    """Return the findings for one PR; empty when it complies.

    Args:
        pull: Everything known about the PR.

    Returns:
        One finding per violated rule.
    """
    findings: list[str] = []
    if not TITLE_RE.match(pull.title):
        findings.append("title must be `<Topic>: <imperative summary>` (a work unit: `WU-NN: …`)")
    if pull.author in BOT_AUTHORS or GENERATED_TITLE_RE.match(pull.title):
        return findings
    present = sections(pull.body)
    missing = [h for h in MANDATORY_SECTIONS if h not in present]
    if missing:
        findings.append("body is missing mandatory sections: " + ", ".join(missing))
    if pull.base and pull.base != "main" and not STACKED_RE.search(pull.body):
        findings.append(f"base is `{pull.base}`: the body must say `Stacked on #N`")
    if pull.draft:
        return findings

    for heading, text in present.items():
        if not has_content(text):
            optional = " or delete the section" if heading not in MANDATORY_SECTIONS else ""
            findings.append(f"{heading} has no content: fill it{optional}")
    if PLACEHOLDER_RE.search(without_code(COMMENT_RE.sub("", pull.body))):
        findings.append("ready for review but template placeholders remain (<…>)")
    return findings


def _run(argv: list[str]) -> str:
    """Run a command in the repo root and return stdout (empty on failure)."""
    proc = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, check=False)
    return proc.stdout if proc.returncode == 0 else ""


def main(argv: list[str] | None = None) -> int:
    """Entry point.

    Args:
        argv: Command-line arguments, defaulting to `sys.argv[1:]`.

    Returns:
        0 when the PR complies, 1 otherwise.
    """
    parser = argparse.ArgumentParser(description="Check a PR title and body against the template.")
    parser.add_argument("--pr", type=int, help="fetch the PR with gh instead of passing fields")
    parser.add_argument("--title", default="")
    parser.add_argument("--body-file")
    parser.add_argument("--draft", action="store_true")
    parser.add_argument("--base", default="main")
    parser.add_argument(
        "--author", default="", help="PR author login (bots get a title-only check)"
    )
    args = parser.parse_args(argv)

    if args.pr:
        raw = _run(
            ["gh", "pr", "view", str(args.pr), "--json", "title,body,isDraft,baseRefName,author"]
        )
        if not raw:
            print(f"could not fetch PR #{args.pr} with gh")
            return 1
        data: dict[str, Any] = json.loads(raw)
        author_raw: Any = data.get("author", {})
        pull = Pull(
            title=str(data["title"]),
            body=str(data["body"] or ""),
            draft=bool(data["isDraft"]),
            base=str(data["baseRefName"]),
            author=(
                str(cast("dict[str, Any]", author_raw).get("login", ""))
                if isinstance(author_raw, dict)
                else ""
            ),
        )
    else:
        body = Path(args.body_file).read_text(encoding="utf-8") if args.body_file else ""
        pull = Pull(args.title, body, args.draft, args.base, args.author)

    findings = check(pull)
    label = "draft" if pull.draft else "ready"
    if pull.author in BOT_AUTHORS:
        label += f", bot {pull.author}"
    elif GENERATED_TITLE_RE.match(pull.title):
        label += ", generated release PR"
    if findings:
        print(f"PR HYGIENE ({label}, base {pull.base}): {len(findings)} finding(s)")
        for f in findings:
            print("  - " + f)
        print("Template: .github/PULL_REQUEST_TEMPLATE.md")
        return 1
    print(f"pr hygiene: ok ({label}, base {pull.base})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
